import { expect, it } from "vitest";
import { formatPhone } from "./phone";

it.each([
  ["01012345678", "010-1234-5678"],
  ["0212345678", "02-1234-5678"],
  ["021234567", "02-123-4567"],
  ["0511234567", "051-123-4567"],
  ["03112345678", "031-1234-5678"],
  ["15881234", "1588-1234"],
  ["050512345678", "0505-1234-5678"],
  ["010-1234-5678", "010-1234-5678"],
  ["", ""],
  ["+82 10 1234 5678", "+82 10 1234 5678"],
  ["0511234567 내선 2", "0511234567 내선 2"],
])("formats %s without losing phone content", (input, result) => {
  expect(formatPhone(input)).toBe(result);
});
